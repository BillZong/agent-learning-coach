"""存储层的错误类型。

**为什么不用 ``DomainError``**：领域错误说「这个事实不合法」，存储错误说「这次存
取没成功」——两者的处理方式不同：领域错误要修数据，存储错误要重试或改代码。混在
一起，调用方分不清该修数据还是该报警。

**但领域错误仍然会从解码里冒出来**：从存储读回的数据要经过领域对象的构造校验，
不合法的事实**在读回时就被拒绝**——这正是「写入路径复用领域层不变量」在读侧的
体现（ADR-0026）。那类错误仍然是 ``DomainError``，因为它说的确实是「这个事实
不合法」。
"""

from __future__ import annotations


class StorageError(Exception):
    """存储操作失败。"""


class DecodeError(StorageError):
    """负载无法解码。

    负载的结构不对——缺字段、类型不对、schema 版本不认识。**它不是领域错误**：
    领域对象根本没被构造出来。
    """


class ConflictError(StorageError):
    """乐观锁冲突。

    要写的记录是基于某个旧版本读出来的，而存储里的版本已经变了（别人先写了）。
    读-改-写之间的那段时间里，数据被别人改了。
    """
